#pragma once

/* =====================================================================
   core.h  --  Игровые типы, структуры, прототипы логики
   Правило: НИКАКИХ #include <windows.h> здесь и в core.c
   ===================================================================== */

#define ARENA_W      800       /* ширина арены в пикселях               */
#define ARENA_H      600       /* высота арены в пикселях               */
#define MAX_ENEMIES  128
#define MAX_BULLETS  256
#define MAX_GEMS     128
#define UPGRADE_COUNT 6        /* количество возможных апгрейдов        */

/* --------------------------------------------------------------------- */
/*  Фазы игры                                                            */
/* --------------------------------------------------------------------- */
typedef enum {
    PHASE_MENU,                /* экран выбора сложности                */
    PHASE_PLAYING,             /* идёт волна                            */
    PHASE_UPGRADE,             /* экран выбора апгрейда между волнами   */
    PHASE_DEAD,                /* игрок умер                            */
    PHASE_WIN                  /* пережил все волны                     */
} GamePhase;

/* --------------------------------------------------------------------- */
/*  Состояние клавиш  (заполняется в ui.c, читается в core.c)           */
/* --------------------------------------------------------------------- */
typedef struct {
    int up, down, left, right; /* WASD / стрелки                        */
    int select1, select2, select3; /* 1/2/3 — выбор апгрейда           */
    int restart;               /* R — перезапуск                        */
} InputState;

/* --------------------------------------------------------------------- */
/*  Игрок                                                                */
/* --------------------------------------------------------------------- */
typedef struct {
    float x, y;                /* позиция центра                        */
    float speed;               /* пикселей в секунду                    */
    int   hp, maxHp;
    float fireTimer;           /* секунд до следующего выстрела         */
    float fireCooldown;        /* базовый кулдаун                       */
    float bulletSpeed;
    int   bulletDamage;
    int   xp;                  /* накоплено за волну                    */
    int   xpToNext;            /* нужно для левел-апа (резерв)         */
    float invTimer;            /* таймер неуязвимости после удара       */
    int   upgrades[UPGRADE_COUNT]; /* количество каждого апгрейда      */
} Player;

/* --------------------------------------------------------------------- */
/*  Виды врагов                                                          */
/* --------------------------------------------------------------------- */
typedef enum {
    ENEMY_BASIC  = 0,          /* медленный, мало HP                   */
    ENEMY_FAST   = 1,          /* быстрый, мало HP                     */
    ENEMY_TANK   = 2           /* медленный, много HP                  */
} EnemyType;

/* --------------------------------------------------------------------- */
/*  Враг                                                                 */
/* --------------------------------------------------------------------- */
typedef struct {
    float     x, y;
    float     speed;
    int       hp, maxHp;
    int       damage;          /* урон при касании                      */
    EnemyType type;
    int       alive;           /* 0 = слот свободен                     */
} Enemy;

/* --------------------------------------------------------------------- */
/*  Пуля                                                                 */
/* --------------------------------------------------------------------- */
typedef struct {
    float x, y;
    float vx, vy;              /* вектор скорости                       */
    int   damage;
    int   alive;
} Bullet;

/* --------------------------------------------------------------------- */
/*  Гем опыта                                                            */
/* --------------------------------------------------------------------- */
typedef struct {
    float x, y;
    int   value;
    int   alive;
} XpGem;

/* --------------------------------------------------------------------- */
/*  Описание апгрейда (для экрана выбора)                               */
/* --------------------------------------------------------------------- */
typedef struct {
    int   id;
    const char *name;
    const char *desc;
} UpgradeInfo;

/* --------------------------------------------------------------------- */
/*  Полное состояние игры  — единственный объект, гуляющий по всему коду */
/* --------------------------------------------------------------------- */
typedef struct {
    Player     player;
    Enemy      enemies[MAX_ENEMIES];
    Bullet     bullets[MAX_BULLETS];
    XpGem      gems[MAX_GEMS];

    int        wave;           /* текущий номер волны (1-based)         */
    int        totalWaves;     /* всего волн до победы                  */
    int        enemiesLeft;    /* врагов осталось в волне               */
    float      spawnTimer;     /* таймер спавна внутри волны            */
    float      spawnInterval;  /* секунд между спавнами                 */

    int        score;
    GamePhase  phase;

    /* сложность: 0=лёгкая 1=нормальная 2=сложная                       */
    int        difficulty;
    float      hpScalePerWave; /* коэффициент роста HP врагов за волну  */

    /* экран апгрейда: три варианта на выбор                            */
    int        offerIds[3];    /* id предложенных апгрейдов             */

    InputState input;          /* текущее состояние ввода               */
} GameState;

/* --------------------------------------------------------------------- */
/*  Публичные функции модуля core                                        */
/* --------------------------------------------------------------------- */
void Core_Init          (GameState *gs);
void Core_SetDifficulty (GameState *gs, int difficulty); /* 0/1/2 */
void Core_Update     (GameState *gs, float dt);
void Core_StartWave  (GameState *gs);
void Core_ApplyUpgrade(GameState *gs, int upgradeId);

/* Описания апгрейдов (для рендера экрана выбора в ui.c)               */
const UpgradeInfo *Core_GetUpgradeInfo(int id);
